import { test, expect } from '@playwright/test';

test('ordem simulada: agente correto, prévia, foco, pausa, Kanban e persistência', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto('/');
  await page.getByRole('button', { name: 'Selecionar Sofia Almeida, Trabalhando' }).click();
  let panel = page.getByRole('complementary', { name: 'Detalhes de Sofia Almeida' });
  await expect(panel.locator('.current-task')).toContainText('O mistério das cidades submersas');
  const brief = 'Crie um roteiro de 30 segundos sobre auroras, com um gancho inicial.';
  const external: string[] = [];
  page.on('request', req => { if (!['127.0.0.1', 'localhost'].includes(new URL(req.url()).hostname)) external.push(req.url()); });
  await panel.getByLabel('Ordem para o agente', { exact: true }).fill(brief);
  await panel.getByLabel('Canal da ordem', { exact: true }).selectOption('mundo');
  await panel.getByRole('button', { name: 'Enviar ordem', exact: true }).click();
  await expect(panel.locator('.current-task')).toContainText(brief);
  await expect(panel.locator('.agent-preview pre')).toContainText('MODELO LOCAL, SEM IA');
  await expect(panel.locator('.agent-preview pre')).toContainText(brief);
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('jmm-studios-v1')!).state);
  const task = saved.tasks.find((t: { instructions?: string }) => t.instructions === brief);
  expect(task.agentId).toBe('writer');
  expect(task.channelId).toBe('mundo');
  expect(task.stage).toBe('Roteiro');
  expect(task.preview.kind).toBe('simulation');
  expect(saved.currentTaskIds.writer).toBe(task.id);
  await panel.getByRole('heading', { name: 'Central do agente', exact: true }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: 'test-results/ordem-recebida.png', fullPage: true });
  await panel.getByRole('button', { name: 'Pausar trabalho', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Selecionar Sofia Almeida, Em pausa' })).toBeVisible();
  await expect(panel.getByRole('button', { name: 'Avançar etapa', exact: true })).toBeDisabled();
  await panel.getByRole('button', { name: 'Retomar', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Selecionar Sofia Almeida, Trabalhando' })).toBeVisible();
  await panel.getByRole('button', { name: 'Avançar etapa', exact: true }).click();
  await expect(panel.locator('.current-task .progress-caption')).toContainText('Cenas');
  await page.reload();
  await page.getByRole('button', { name: /^Agentes \d+$/ }).click();
  await page.getByRole('button').filter({ has: page.getByRole('heading', { name: 'Sofia Almeida', exact: true }) }).click();
  panel = page.getByRole('complementary', { name: 'Detalhes de Sofia Almeida' });
  await expect(panel.getByLabel('Tarefa em foco', { exact: true })).toHaveValue(task.id);
  await expect(panel.locator('.current-task .progress-caption')).toContainText('Cenas');
  await expect(panel.locator('.agent-preview pre')).toContainText(brief);
  await panel.getByLabel('Tarefa em foco', { exact: true }).selectOption('demo-1');
  await expect(panel.locator('.current-task')).toContainText('O mistério das cidades submersas');
  await panel.getByLabel('Tarefa em foco', { exact: true }).selectOption(task.id);
  await panel.getByRole('button', { name: 'Concluir tarefa', exact: true }).click();
  await expect(panel.locator('.assigned-tasks')).toContainText('Concluído');
  await panel.locator('.agent-preview summary').click();
  await expect(panel.locator('.agent-preview pre')).toBeVisible();
  await page.getByRole('button', { name: 'Produção', exact: true }).click();
  await expect(page.getByLabel(`Etapa de ${brief}`, { exact: true })).toHaveValue('Concluído');
  await page.screenshot({ path: 'test-results/ordens-agente-desktop.png', fullPage: true });
  expect(errors).toEqual([]);
  expect(external).toEqual([]);
});

test('celular: rascunho não passa para outro agente e ordem aceita sem tarefa prévia', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/');
  await page.getByRole('button', { name: 'Abrir menu' }).click();
  await page.getByRole('button', { name: /^Agentes \d+$/ }).click();
  await page.getByRole('button').filter({ has: page.getByRole('heading', { name: 'Marina Costa', exact: true }) }).click();
  let panel = page.getByRole('complementary', { name: 'Detalhes de Marina Costa' });
  await expect(panel.getByRole('button', { name: 'Iniciar tarefa', exact: true })).toBeDisabled();
  await panel.getByLabel('Ordem para o agente', { exact: true }).fill('Rascunho privado de Marina');
  await panel.getByRole('button', { name: 'Fechar painel' }).click();
  await page.getByRole('button').filter({ has: page.getByRole('heading', { name: 'Lucas Mendes', exact: true }) }).click();
  panel = page.getByRole('complementary', { name: 'Detalhes de Lucas Mendes' });
  await expect(panel.getByLabel('Ordem para o agente', { exact: true })).toHaveValue('');
  await panel.getByLabel('Ordem para o agente', { exact: true }).fill('  ');
  await expect(panel.getByRole('button', { name: 'Enviar ordem', exact: true })).toBeDisabled();
  await panel.getByRole('button', { name: 'Fechar painel' }).click();
  await page.getByRole('button').filter({ has: page.getByRole('heading', { name: 'Marina Costa', exact: true }) }).click();
  panel = page.getByRole('complementary', { name: 'Detalhes de Marina Costa' });
  const brief = 'Defina a proposta de um vídeo sobre astronomia.';
  await panel.getByLabel('Ordem para o agente', { exact: true }).fill(brief);
  await panel.getByRole('button', { name: 'Enviar ordem', exact: true }).click();
  await expect(panel.locator('.current-task')).toContainText(brief);
  await expect(panel.getByRole('button', { name: 'Pausar trabalho', exact: true })).toBeEnabled();
  await expect(panel.locator('.agent-preview pre')).toContainText('Agente: Marina Costa');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/ordens-agente-mobile.png', fullPage: true });
});
